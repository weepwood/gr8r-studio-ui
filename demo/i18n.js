/** Map any BCP 47 tag to a gallery locale. */
export function matchLocale(tag) {
  return /^zh\b/i.test(String(tag || "")) ? "zh-CN" : "en";
}
/** Saved choice, then the browser's language list. */
export function preferredLocale(saved, languages = []) {
  if (LOCALES.includes(saved)) return saved;
  return matchLocale([...languages].find(Boolean));
}

export function format(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(vars, name) ? String(vars[name]) : match);
}
export function message(locale, key, vars) {
  const table = MESSAGES[locale] || MESSAGES.en;
  return format(table[key] ?? MESSAGES.en[key] ?? key, vars);
}

let reverse;
/** Exact phrase lookup in either direction; unknown text is returned unchanged. */
export function phrase(text, locale) {
  const key = String(text).replace(/\s+/g, " ").trim();
  if (locale === "zh-CN") return PHRASES[key] ?? text;
  reverse ||= Object.fromEntries(Object.entries(PHRASES).map(([en, zh]) => [zh, en]));
  return reverse[key] ?? text;
}

const ATTRIBUTES = ["aria-label", "placeholder", "data-gr-tooltip", "data-toast", "label", "title"];
const SKIP = "pre, code, kbd, .gr-kbd, script, style, noscript, [data-i18n-skip], .demo-code-view";

/** Translate the text and labelled attributes of a subtree into `locale`, in place. */
export function translateTree(root, locale) {
  if (!root) return;
  const doc = root.ownerDocument || root;
  const walker = doc.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: node => node.parentElement?.closest(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
  });
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.data;
    const core = text.trim();
    if (!core || !/[A-Za-z\u4e00-\u9fff]/.test(core)) continue;
    const next = phrase(core, locale);
    if (next !== core) node.data = text.slice(0, text.indexOf(core)) + next + text.slice(text.indexOf(core) + core.length);
  }
  const elements = root.nodeType === 1 ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
  for (const element of elements) {
    if (element.closest(SKIP)) continue;
    for (const name of ATTRIBUTES) {
      const value = element.getAttribute(name);
      if (!value) continue;
      const next = phrase(value, locale);
      if (next !== value) element.setAttribute(name, next);
    }
  }
}
